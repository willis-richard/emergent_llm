class Strategy_SELFISH_8(BaseStrategy):
    """
    Pivotal Contributor: cooperate only when contribution is likely pivotal,
    using a recency-weighted estimate of opponent cooperators and binomial
    pivotality checks; includes anti-exploitation defect spells and special
    handling for m == n.
    """

    def __init__(self, game_description: CollectiveRiskDescription):
        self.g = game_description
        self.ohat = 0.0
        self.consec_fail_coop = 0
        self.defect_timer = 0
        self.gave_up = False

    def _binom_pmf(self, j, n, p):
        if j < 0 or j > n:
            return 0.0
        return math.comb(n, j) * p ** j * (1 - p) ** (n - j)

    def _binom_sf(self, m, n, p):
        return sum((self._binom_pmf(j, n, p) for j in range(m, n + 1)))

    def __call__(self, history: PlayerHistory) -> Action:
        g = self.g
        n, m, k, r = (g.n_players, g.m, g.k, g.n_rounds)
        t = history.round_number
        if t > 0:
            o = int(history.opponent_cooperators[-1])
            if t == 1:
                self.ohat = float(o)
            else:
                self.ohat = 0.6 * self.ohat + 0.4 * o
            total = o + (1 if history.my_actions[-1] else 0)
            if history.my_actions[-1] and total < m:
                self.consec_fail_coop += 1
            else:
                self.consec_fail_coop = 0
            if m == n and total < m:
                self.gave_up = True
        if m == n:
            if self.gave_up:
                return Action.D
            return Action.C
        if t == 0:
            return Action.C if m <= math.ceil(2 * n / 3) else Action.D
        if self.defect_timer > 0:
            self.defect_timer -= 1
            return Action.D
        if self.consec_fail_coop >= 3:
            self.defect_timer = 1
            self.consec_fail_coop = 0
            return Action.D
        denom = max(n - 1, 1)
        p = min(max(self.ohat / denom, 0.0), 1.0)
        P_piv = self._binom_pmf(m - 1, n - 1, p)
        if t == r - 1:
            if self.ohat >= m:
                return Action.D
            return Action.C if k * P_piv > 1 else Action.D
        if self.ohat >= m + 0.5:
            return Action.D
        if self._binom_sf(m, n - 1, p) > 0.9:
            return Action.D
        if k * P_piv > 1:
            return Action.C
        if abs(self.ohat - (m - 1)) <= 1.5:
            return Action.C
        return Action.D

