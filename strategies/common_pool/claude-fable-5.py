class Strategy_OPPORTUNISTIC_2(BaseStrategy):
    """
    Opportunistic Free-Rider with Sustainability Guardrails:
    defect when stock can absorb it or future doesn't matter;
    cooperate only as a worthwhile investment.
    """

    def __init__(self, game_description: CommonPoolDescription):
        self.game_description = game_description
        self.coop_rate = 1.0
        self.prev_stocks = []

    def _project(self, S, my_consumption):
        n = self.game_description.n_players
        cap = self.game_description.capacity
        others = (n - 1) * (self.coop_rate * S / (2 * n) + (1 - self.coop_rate) * S / n)
        S_rem = max(S - my_consumption - others, 0.0)
        growth = 2 * S_rem * (1 - S_rem / cap) if cap > 0 else 0.0
        return min(S_rem + growth, cap)

    def __call__(self, history: PlayerHistory, current_stock: float) -> Action:
        n = self.game_description.n_players
        r = self.game_description.n_rounds
        cap = float(self.game_description.capacity)
        t = history.round_number
        S = current_stock
        if t > 0 and n > 1:
            observed = history.opponent_cooperators[-1] / (n - 1)
            self.coop_rate = 0.5 * self.coop_rate + 0.5 * observed
        self.prev_stocks.append(S)
        if t >= r - 2:
            return Action.D
        if t == r - 3 and self.coop_rate < 0.5:
            return Action.D
        if S < 0.05 * cap:
            return Action.D
        S_next = self._project(S, S / n)
        S_next_C = self._project(S, S / (2 * n))
        if S_next >= 0.6 * cap:
            return Action.D
        if len(self.prev_stocks) >= 3 and self.coop_rate < 0.5 and (self.prev_stocks[-1] < self.prev_stocks[-2] < self.prev_stocks[-3]):
            return Action.D
        threshold = (n - 2) / (n - 1) if n > 1 else 0.0
        if S_next_C - S_next >= 0.1 * cap and self.coop_rate >= threshold and (r - t >= 3):
            return Action.C
        return Action.D

