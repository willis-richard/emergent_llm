class Strategy_INDIVIDUALISTIC_1(BaseStrategy):
    """
    Harvest-Guard: sustainable extraction with contingent, escalating punishment,
    end-game defection, stock-collapse override, and grim fallback.
    """

    def __init__(self, game_description: CommonPoolDescription):
        self.game_description = game_description
        self.punish_timer = 0
        self.escalation = 1
        self.minor_streak = 0
        self.just_punished = False
        self.grim = False

    def _start_punishment(self):
        self.punish_timer = self.escalation
        self.escalation = min(self.escalation + 1, 4)
        self.minor_streak = 0
        return Action.D

    def __call__(self, history: PlayerHistory, current_stock: float) -> Action:
        n = self.game_description.n_players
        r = self.game_description.n_rounds
        cap = float(self.game_description.capacity)
        t = history.round_number
        if t == 0:
            return Action.C
        if t >= r - 1:
            return Action.D
        if t == r - 2 and current_stock >= 0.5 * cap:
            return Action.D
        opp = max(n - 1, 1)
        d = opp - int(history.opponent_cooperators[-1])
        coop_last = int(history.opponent_cooperators[-1])
        if t >= r - 3 and coop_last / opp < 0.5:
            return Action.D
        if current_stock < 0.1 * cap:
            return Action.D
        if current_stock < 0.4 * cap:
            return Action.C if coop_last >= math.ceil(opp / 2) else Action.D
        total_coop = float(np.sum(history.opponent_cooperators))
        if self.grim or total_coop / (opp * t) < 0.3:
            self.grim = True
            return Action.D
        if self.punish_timer > 0:
            self.punish_timer -= 1
            if self.punish_timer == 0:
                self.just_punished = True
            return Action.D
        minor_thresh = (n - 1) // 3
        if self.just_punished:
            self.just_punished = False
            if d <= minor_thresh:
                if d == 0:
                    self.minor_streak = 0
                return Action.C
            return self._start_punishment()
        if d == 0:
            self.minor_streak = 0
            return Action.C
        if d <= minor_thresh:
            self.minor_streak += 1
            if self.minor_streak >= 3:
                return self._start_punishment()
            return Action.C
        return self._start_punishment()

class Strategy_INDIVIDUALISTIC_2(BaseStrategy):
    """
    Sustainable Extraction with Threshold Retaliation (SETR).
    Cooperates instrumentally when opponents cooperate and stock is healthy;
    defects at endgame, on depleted stock, against defecting majorities,
    as one-round punishment for cooperation drops, and as a periodic probe.
    """

    def __init__(self, game_description: CommonPoolDescription):
        self.game_description = game_description

    def __call__(self, history: PlayerHistory, current_stock: float) -> Action:
        n = self.game_description.n_players
        r = self.game_description.n_rounds
        cap = self.game_description.capacity
        t = history.round_number
        opp = n - 1
        if t == r - 1:
            return Action.D
        if t == r - 2:
            if n >= 4:
                return Action.D
            if t == 0:
                return Action.C
            return Action.C if history.opponent_cooperators[-1] == opp else Action.D
        if t == 0:
            return Action.C
        rho = current_stock / cap if cap > 0 else 0.0
        f = history.opponent_cooperators[-1] / opp if opp > 0 else 1.0
        if rho < 0.2 or f < 0.5:
            return Action.D
        if t >= 2:
            drop = history.opponent_cooperators[-1] - history.opponent_cooperators[-2]
            if drop <= -math.ceil(0.25 * opp):
                return Action.D
        if n > 3 and rho >= 1.0 and (t >= 3) and (t % 4 == 3):
            if all((history.opponent_cooperators[-k] == opp for k in (1, 2, 3))):
                return Action.D
        return Action.C

class Strategy_INDIVIDUALISTIC_3(BaseStrategy):
    """
    Harvest-Guard: sustainable extraction with conditional punishment.
    Cooperates only to keep the stock high for future extraction; punishes
    defection waves and defects in the endgame.
    """

    def __init__(self, game_description: CommonPoolDescription):
        self.game_description = game_description
        self.pun = 0
        self.last_stock = None
        self.last_action_was_c = False
        self.low_stock_defect = False

    def __call__(self, history: PlayerHistory, current_stock: float) -> Action:
        n = self.game_description.n_players
        r = self.game_description.n_rounds
        cap = float(self.game_description.capacity)
        t = history.round_number
        S = current_stock
        prev_stock = self.last_stock
        prev_was_c = self.last_action_was_c
        self.last_stock = S

        def ret(a: Action) -> Action:
            self.last_action_was_c = a == Action.C
            return a
        if t == r - 1:
            return ret(Action.D)
        if S < 0.05 * cap:
            return ret(Action.D)
        if t == 0:
            return ret(Action.C)
        opp = max(n - 1, 1)
        f = history.opponent_cooperators[-1] / opp
        if t == r - 2:
            return ret(Action.C if f >= 0.5 else Action.D)
        if t == r - 3 and f < 0.7:
            return ret(Action.D)
        if self.pun > 0:
            if f >= 0.7:
                self.pun = 0
            else:
                self.pun -= 1
                return ret(Action.D)
        if S >= 0.4 * cap:
            self.low_stock_defect = False
        if f >= 0.5 and S >= 0.4 * cap:
            return ret(Action.C)
        if f >= 0.5:
            if prev_was_c and prev_stock is not None and (S <= prev_stock):
                self.low_stock_defect = True
            if self.low_stock_defect:
                return ret(Action.D)
            return ret(Action.C)
        self.pun = 1
        return ret(Action.D)

class Strategy_INDIVIDUALISTIC_4(BaseStrategy):
    """
    Harvest-Guard: sustainable extraction with trigger response,
    endgame defection, stock-collapse override, conditional
    forgiveness, and periodic re-entry probes.
    """

    def __init__(self, game_description: CommonPoolDescription):
        self.game_description = game_description
        self.consec_defects = 0
        self.probe_round = None
        self.no_probe_until = -1

    def __call__(self, history: PlayerHistory, current_stock: float) -> Action:
        n = self.game_description.n_players
        r = self.game_description.n_rounds
        cap = float(self.game_description.capacity)
        t = history.round_number

        def record(action, rule5_defect=False):
            if rule5_defect:
                self.consec_defects += 1
            else:
                self.consec_defects = 0
            return action
        if self.probe_round is not None and t == self.probe_round + 1:
            denom = max(n - 1, 1)
            if history.opponent_cooperators[-1] / denom >= 0.5:
                self.consec_defects = 0
            else:
                self.no_probe_until = t + 4
            self.probe_round = None
        if t == 0:
            return record(Action.C)
        last_coop = int(history.opponent_cooperators[-1])
        if t == r - 1:
            return record(Action.D)
        if t == r - 2:
            if n == 2 and last_coop == n - 1:
                return record(Action.C)
            return record(Action.D)
        if current_stock < 0.15 * cap:
            return record(Action.D)
        denom = max(n - 1, 1)
        f = last_coop / denom
        threshold = (n - 2) / denom
        if f >= threshold:
            return record(Action.C)
        if f < 0.5:
            if self.consec_defects >= 3 and current_stock >= 0.4 * cap and (r - t >= 4) and (t >= self.no_probe_until):
                self.probe_round = t
                return record(Action.C)
            return record(Action.D, rule5_defect=True)
        prev2 = int(history.opponent_cooperators[-2]) if t >= 2 else 0
        if current_stock >= 0.6 * cap and last_coop >= prev2:
            return record(Action.C)
        if self.consec_defects >= 3 and current_stock >= 0.4 * cap and (r - t >= 4) and (t >= self.no_probe_until):
            self.probe_round = t
            return record(Action.C)
        return record(Action.D, rule5_defect=True)

