        n = self.game_description.n_players
        r = self.game_description.n_rounds
        K = self.game_description.capacity
        t = history.round_number
        prev = self.prev_stock
        self.prev_stock = current_stock
        if t == 0:
            return self._play(Action.C)
        coop_prev = int(history.opponent_cooperators[-1])
        opp = max(n - 1, 1)
        if current_stock < 0.2 * K:
            return self._play(Action.C)
        if t == r - 1:
            if coop_prev >= math.ceil(opp / 2):
                return self._play(Action.C)
            return self._play(Action.D)
