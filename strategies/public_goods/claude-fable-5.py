        n = game_description.n_players
        r = game_description.n_rounds
        k = game_description.k
        self.E = max(2, math.ceil(r / 10))
        self.T = max(1, math.ceil(n / k) - 1)
        self.low = math.ceil((n - 1) / 3)
        self.p = 1.0 / 3.0
        self.rebuild = 0
        self.last_defected_healthy = False
        self.probe_interval = max(1, math.ceil(r / 5))

