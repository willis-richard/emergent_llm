class Strategy_PROSOCIAL_3(BaseStrategy):
    """
    Generous Threshold Reciprocator: EWMA cooperation index with threshold
    theta=(k-1)/k clipped to [0.3,0.7], probabilistic forgiveness, olive
    branch after 2 consecutive defections, fast punishment/forgiveness
    overlay, and last-round rule (cooperate iff W >= 0.8).
    """

    def __init__(self, game_description: PublicGoodsDescription):
        self.gd = game_description
        self.m = max(1, game_description.n_players - 1)
        k = game_description.k
        theta = (k - 1.0) / k if k != 0 else 0.5
        self.theta = min(0.7, max(0.3, theta))
        self.alpha = 0.5
        self.W = 1.0
        self.last_processed = 0
        self.defect_streak = 0

    def _update(self, history):
        t = history.round_number
        while self.last_processed < t:
            i = self.last_processed
            frac = history.opponent_cooperators[i] / self.m
            self.W = self.alpha * self.W + (1 - self.alpha) * frac
            self.last_processed += 1
        streak = 0
        for a in reversed(history.my_actions):
            if not a:
                streak += 1
            else:
                break
        self.defect_streak = streak

    def __call__(self, history: PlayerHistory) -> Action:
        t = history.round_number
        r = self.gd.n_rounds
        if t == 0:
            return Action.C
        self._update(history)
        coop_last = history.opponent_cooperators[-1]
        if t == r - 1:
            if r == 2:
                return Action.C if coop_last == self.m else Action.D
            return Action.C if self.W >= 0.8 else Action.D
        if self.defect_streak >= 2:
            return Action.C
        if coop_last == self.m:
            return Action.C
        if t >= 2 and coop_last == 0 and (history.opponent_cooperators[-2] == 0):
            return Action.D
        if self.W >= self.theta:
            return Action.C
        p = max(0.1, self.W)
        if random.random() < p:
            return Action.C
        return Action.D

