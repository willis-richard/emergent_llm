class Strategy_INDIVIDUALISTIC_1(BaseStrategy):
    """
    Exploitative Threshold Reciprocator:
    - Cooperate round 0 as a probe.
    - Cooperate if last-round opponent cooperators >= T = ceil(n/k)-1;
      forgive once at half-threshold; otherwise defect.
    - Lock into defection if defecting pays better and population is unresponsive.
    - Defect in final E rounds (endgame).
    """

    def __init__(self, game_description: PublicGoodsDescription):
        self.game_description = game_description
        n = game_description.n_players
        r = game_description.n_rounds
        k = game_description.k
        self.T = math.ceil(n / k) - 1
        self.E = 1 if r < 8 else 2 if r < 20 else 3
        self.f = 1
        self.locked_defect = False

    def _exploitation_check(self, history: PlayerHistory) -> None:
        t = history.round_number
        if t < 3:
            return
        w = min(5, t)
        acts = history.my_actions[-w:]
        pays = history.my_payoffs[-w:]
        coop_pays = [p for a, p in zip(acts, pays) if a]
        def_pays = [p for a, p in zip(acts, pays) if not a]
        if not coop_pays or not def_pays:
            return
        if np.mean(def_pays) <= np.mean(coop_pays):
            return
        if history.my_actions[-1] != history.my_actions[-2]:
            if abs(int(history.opponent_cooperators[-1]) - int(history.opponent_cooperators[-2])) <= 1:
                self.locked_defect = True

    def __call__(self, history: PlayerHistory) -> Action:
        t = history.round_number
        r = self.game_description.n_rounds
        if t >= r - self.E:
            return Action.D
        if self.locked_defect:
            return Action.D
        if t == 0:
            return Action.C
        self._exploitation_check(history)
        if self.locked_defect:
            return Action.D
        last = int(history.opponent_cooperators[-1])
        T = self.T
        if T <= 0:
            return Action.C if last >= 1 else Action.D
        if last >= T:
            self.f = 1
            return Action.C
        if last >= math.ceil(T / 2) and self.f > 0:
            self.f -= 1
            return Action.C
        return Action.D

